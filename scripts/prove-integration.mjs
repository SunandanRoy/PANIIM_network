#!/usr/bin/env node
// Integration proof (Gate D): fresh Lovable-style hosts, the install script, the three host edits exactly as
// INTEGRATION.md describes them, then install, build, typecheck and a browser smoke test against the local API.
// Writes docs/INTEGRATION_PROOF.md. Needs the harness API on 127.0.0.1:54321 (pnpm db:setup && pnpm harness:api).
//   node scripts/prove-integration.mjs <work dir>
import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const work = resolve(process.argv[2] ?? join(repo, "harness/proof/.work"));
mkdirSync(work, { recursive: true });
const log = [];
const run = (cmd, cwd, { quiet = false, allowFail = false } = {}) => {
  log.push(`$ ${cmd.replace(work, "<work>").replace(repo, "<repo>")}`);
  try {
    const out = execSync(cmd, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 * 1024 * 1024 });
    const lines = out.trim().split("\n");
    log.push(...(quiet ? lines.slice(-6) : lines).map((l) => l.replaceAll(work, "<work>").replaceAll(repo, "<repo>")));
    return out;
  } catch (e) {
    const out = `${e.stdout ?? ""}${e.stderr ?? ""}`.trim().split("\n");
    log.push(...out.slice(-25).map((l) => l.replaceAll(work, "<work>")), `(exit ${e.status})`);
    if (!allowFail) {
      writeReport(false);
      process.exit(1);
    }
    return "";
  }
};
const edit = (file, from, to) => {
  const s = readFileSync(file, "utf8");
  if (!s.includes(from)) throw new Error(`edit anchor not found in ${file}: ${from}`);
  writeFileSync(file, s.replace(from, to));
};

const results = [];
function writeReport(ok) {
  const body = `# Integration proof

Generated by \`node scripts/prove-integration.mjs\` on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC.
The real Pan-IIM host repo was not available (DECISIONS E-01), so the proof uses two freshly generated
Lovable-style hosts (\`harness/proof/make-host.mjs\`): the older React + Vite template and the TanStack Start
template that Lovable uses for projects created since 13 May 2026.

For each host: generate and commit, run \`scripts/install-into-host.mjs\` (dry run, then for real), make the
three host edits from \`integration/host-edits.md\`, install, build, typecheck, then open the module's routes in
Chromium against the local database through the harness API (signed out, so only \`net_resolve_token\` is used).

## Result: ${ok ? "PASS" : "FAIL"}

| Host | Install | Build | Typecheck | Smoke |
|---|---|---|---|---|
${results.map((r) => `| ${r.kind} | ${r.install} | ${r.build} | ${r.tsc} | ${r.smoke} |`).join("\n")}

## Transcript

\`\`\`text
${log.join("\n")}
\`\`\`
`;
  writeFileSync(join(repo, "docs/INTEGRATION_PROOF.md"), body);
}

for (const kind of ["vite", "tanstack"]) {
  const host = join(work, `host-${kind}`);
  rmSync(host, { recursive: true, force: true });
  const r = { kind: kind === "vite" ? "React + Vite (React 18, RR6, Tailwind 3)" : "TanStack Start (React 19, Vite 8, Tailwind 4)", install: "", build: "", tsc: "", smoke: "" };
  results.push(r);
  log.push("", `######## ${kind} host`);
  run(`node ${join(repo, "harness/proof/make-host.mjs")} ${kind} ${host}`, repo);
  // point the generated client at the local harness API for the smoke test
  edit(join(host, "src/integrations/supabase/client.ts"), "https://example-project.supabase.co", "http://127.0.0.1:54321");
  run("npm install --no-audit --no-fund", host, { quiet: true });
  if (kind === "tanstack") run("npx vite build", host, { quiet: true }); // generates routeTree.gen.ts, as Lovable commits it
  run("git add -A && git -c user.name=proof -c user.email=proof@example.invalid commit -q -m 'lockfile and generated files' && git status --short | wc -l", host);

  run(`node ${join(repo, "scripts/install-into-host.mjs")} --host ${host} --dry-run`, repo, { quiet: true });
  run(`node ${join(repo, "scripts/install-into-host.mjs")} --host ${host}`, repo);
  run(`node ${join(repo, "scripts/install-into-host.mjs")} --host ${host} --branch feat/second-try`, repo, { allowFail: true }); // must refuse: tree not clean
  r.install = "✓";

  // The three host edits, exactly as integration/host-edits.md shows them.
  if (kind === "vite") {
    edit(join(host, "src/pages/Network.tsx"), `import { Link } from "react-router-dom";`,
      `import { Link } from "react-router-dom";\nimport { MyPassButton, VisibilityBanner, NetworkMapCard, MapButton } from "@/features/network";`);
    edit(join(host, "src/pages/Network.tsx"), `<h1 className="text-4xl font-bold">Network</h1>`,
      `<div className="flex justify-end"><MyPassButton /></div>\n      <h1 className="text-4xl font-bold">Network</h1>`);
    edit(join(host, "src/pages/Network.tsx"), `<section>`, `<VisibilityBanner />\n      <NetworkMapCard />\n      <section>`);
    edit(join(host, "src/pages/Network.tsx"), `<div className="rounded-2xl border bg-card p-4">4 connections</div>`,
      `<div className="flex items-center justify-between rounded-2xl border bg-card p-4">4 connections <MapButton /></div>`);
    edit(join(host, "src/App.tsx"), `import NotFound from "./pages/NotFound";`, `import NotFound from "./pages/NotFound";\nimport { NetworkRoot, networkRoutes } from "./network.routes";`);
    edit(join(host, "src/App.tsx"), `      <Routes>`, `      <NetworkRoot>\n      <Routes>`);
    edit(join(host, "src/App.tsx"), `        {/* ADD ALL CUSTOM ROUTES`, `        {networkRoutes()}\n        {/* ADD ALL CUSTOM ROUTES`);
    edit(join(host, "src/App.tsx"), `      </Routes>`, `      </Routes>\n      </NetworkRoot>`);
  } else {
    edit(join(host, "src/components/NetworkPage.tsx"), `import { Link } from "@tanstack/react-router";`,
      `import { Link } from "@tanstack/react-router";\nimport { MyPassButton, VisibilityBanner, NetworkMapCard, MapButton } from "@/features/network";`);
    edit(join(host, "src/components/NetworkPage.tsx"), `<h1 className="text-4xl font-bold">Network</h1>`,
      `<div className="flex justify-end"><MyPassButton /></div>\n      <h1 className="text-4xl font-bold">Network</h1>`);
    edit(join(host, "src/components/NetworkPage.tsx"), `<section>`, `<VisibilityBanner />\n      <NetworkMapCard />\n      <section>`);
    edit(join(host, "src/components/NetworkPage.tsx"), `<div className="rounded-2xl border bg-card p-4">4 connections</div>`,
      `<div className="flex items-center justify-between rounded-2xl border bg-card p-4">4 connections <MapButton /></div>`);
    edit(join(host, "src/routes/__root.tsx"), `import appCss from "../styles.css?url";`, `import appCss from "../styles.css?url";\nimport { NetworkRoot } from "../network.root";`);
    edit(join(host, "src/routes/__root.tsx"), `  return <Outlet />;`, `  return (\n    <NetworkRoot>\n      <Outlet />\n    </NetworkRoot>\n  );`);
  }
  run("git diff --stat", host);
  run("npm install --no-audit --no-fund", host, { quiet: true });
  run("npx vite build", host, { quiet: true });
  r.build = "✓";
  run(kind === "vite" ? "npx tsc -p tsconfig.app.json --noEmit && echo typecheck ok" : "npx tsc --noEmit && echo typecheck ok", host);
  r.tsc = "✓";

  // Browser smoke test: serve the build, open the module routes signed out.
  const port = kind === "vite" ? 4301 : 4302;
  const serve = `npx vite preview --port ${port} --strictPort --host 127.0.0.1`;
  const smoke = join(work, `smoke-${kind}.cjs`);
  writeFileSync(smoke, `
const { chromium } = require("playwright");
const { spawn } = require("child_process");
(async () => {
  const srv = spawn("sh", ["-c", ${JSON.stringify(serve)}], { cwd: ${JSON.stringify(host)}, stdio: "ignore", detached: true });
  const base = "http://127.0.0.1:${port}";
  for (let i = 0; i < 60; i++) { try { await fetch(base + "/network"); break; } catch { await new Promise(r => setTimeout(r, 500)); } }
  const b = await chromium.launch(); const p = await b.newPage(); const errors = [];
  p.on("pageerror", e => errors.push(String(e)));
  const check = async (path, text) => { await p.goto(base + path); await p.getByText(text).first().waitFor({ timeout: 15000 }); console.log("ok", path, "->", JSON.stringify(text)); };
  try {
    await check("/network", "You're visible to other presenters.");
    await check("/t/MEERA000DEM00001", "Sign in to see who this is");
    await check("/t/REV0KED0DEM00009", "This pass was replaced.");
    await check("/t/ZZZZZZZZZZZZZZZZ", "We couldn't read this pass.");
    await p.goto(base + "/network/map");
    await p.waitForURL((u) => String(u).includes("/auth?redirect=%2Fnetwork%2Fmap"), { timeout: 15000 });
    console.log("ok /network/map signed out -> redirected to /auth?redirect=%2Fnetwork%2Fmap");
    if (errors.length) { console.log("page errors:", errors); process.exitCode = 1; }
  } catch (e) { console.log("FAIL", e.message); process.exitCode = 1; }
  await b.close(); process.kill(-srv.pid);
})();
`);
  run(`node ${smoke}`, dirname(require_resolve_playwright()));
  r.smoke = "✓";
}
writeReport(true);
console.log("integration proof: PASS (docs/INTEGRATION_PROOF.md)");

function require_resolve_playwright() {
  // run the smoke script from a directory where `require("playwright")` resolves (pre-installed globally here)
  for (const p of ["/opt/node22/lib/node_modules/playwright", "/usr/local/lib/node_modules/playwright", join(repo, "node_modules/playwright")]) {
    if (existsSync(p)) return join(p, "package.json");
  }
  return join(repo, "package.json");
}
